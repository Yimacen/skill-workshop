import JSZip from 'jszip';
import type { AgentSkill } from '../types/skill';
import {
  generateCiRunnerScript,
  generateCiWorkflowYaml,
  generateCodeownersFile,
  generatePluginsJson,
  generateSyncScript,
} from './skillLinter';

function triggerDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function exportSingleSkillZip(skill: AgentSkill): Promise<void> {
  const zip = new JSZip();
  const root = zip.folder(skill.name);
  if (!root) return;

  root.file('SKILL.md', skill.skillMd);

  for (const file of skill.auxFiles) {
    root.file(file.path, file.content);
  }

  if (skill.evalCases.length > 0) {
    root.file('evals/prompts.json', JSON.stringify(skill.evalCases, null, 2));
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  triggerDownload(blob, `${skill.name}.zip`);
}

export async function exportMarketplaceRepoZip(
  skills: AgentSkill[]
): Promise<void> {
  const zip = new JSZip();
  const root = zip.folder('company-skills-marketplace');
  if (!root) return;

  root.file('CODEOWNERS', generateCodeownersFile(skills));
  root.file('plugins.json', generatePluginsJson(skills));
  root.file('scripts/lint-skills.mjs', generateCiRunnerScript());
  root.file('.github/workflows/skill-lint.yml', generateCiWorkflowYaml());
  root.file('install.sh', generateSyncScript(skills));
  root.file(
    'README.md',
    `# Company Skills Marketplace\n\nGenerated by Skill Workshop.\n\n## 目录结构\n- \`always-on/\`: 全局默认加载的基础 Skill\n- \`core/\`: 平台团队审核的核心跨团队 Skill\n- \`domains/\`: 各业务团队自治目录（见 CODEOWNERS）\n- \`plugins.json\`: Skill 插件包分组清单（aifx plugin add）\n- \`scripts/lint-skills.mjs\`: 与工作台同源的 CI 检查脚本\n\n## 本地同步\n\`\`\`bash\nbash install.sh\n\`\`\`\n`
  );

  for (const skill of skills) {
    const baseDir =
      skill.tier === 'always-on'
        ? `always-on/${skill.name}`
        : skill.tier === 'core'
          ? `core/${skill.name}`
          : `domains/${skill.domain || 'general'}/${skill.name}`;

    root.file(`${baseDir}/SKILL.md`, skill.skillMd);
    for (const aux of skill.auxFiles) {
      root.file(`${baseDir}/${aux.path}`, aux.content);
    }
    if (skill.evalCases.length > 0) {
      root.file(
        `${baseDir}/evals/prompts.json`,
        JSON.stringify(skill.evalCases, null, 2)
      );
    }
  }

  const blob = await zip.generateAsync({ type: 'blob' });
  triggerDownload(blob, 'company-skills-marketplace.zip');
}
